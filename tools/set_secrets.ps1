# Prompts for Wi-Fi and Google API credentials and writes include\secrets.h
# Run from anywhere:  powershell -ExecutionPolicy Bypass -File tools\set_secrets.ps1

$ssid = Read-Host "Wi-Fi name (SSID, 2.4 GHz)"
$pwSecure = Read-Host "Wi-Fi password" -AsSecureString
$keySecure = Read-Host "Google API key" -AsSecureString
$origin = Read-Host "Origin address (e.g. Work)"
$dest = Read-Host "Destination address (e.g. Home)"

function Unprotect($s) {
    [Runtime.InteropServices.Marshal]::PtrToStringAuto(
        [Runtime.InteropServices.Marshal]::SecureStringToBSTR($s))
}
function Escape($s) { $s.Replace('\', '\\').Replace('"', '\"') }

$pw = Unprotect $pwSecure
$key = (Unprotect $keySecure).Trim()

$content = @"
#pragma once
// Generated by tools/set_secrets.ps1 - git-ignored, do not commit.
#define WIFI_SSID           "$(Escape $ssid)"
#define WIFI_PASSWORD       "$(Escape $pw)"
#define GOOGLE_MAPS_API_KEY "$(Escape $key)"
#define ORIGIN_ADDRESS      "$(Escape $origin)"
#define DESTINATION_ADDRESS "$(Escape $dest)"
"@

$path = Join-Path $PSScriptRoot "..\include\secrets.h"
Set-Content -Path $path -Value $content -Encoding ASCII
Write-Host "Wrote $((Resolve-Path $path).Path)" -ForegroundColor Green
